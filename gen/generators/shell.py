"""Generate shell install script."""

from ..types import PackageConfig


def generate_shell(
    config: PackageConfig,
    version: str,
) -> str:
    """Render an install.sh script for the package.

    This is a standalone install script that downloads and installs the binary.
    It does NOT depend on tribucket CLI.

    Args:
        config: Package configuration.
        version: Version string (for fallback).

    Returns:
        Shell script content as string.
    """
    name = config.name
    repo = config.repo
    binary = config.binary

    script = f"""#!/usr/bin/env bash
set -euo pipefail

# === tribucket-generated install.sh ===
# Package: {name}
# Repo: {repo}
# Generated by tribucket — do not edit manually.
# Regenerate with: tribucket generate --only {name}

REPO="{repo}"
NAME="{name}"
BINARY="{binary}"
VERSION="${{VERSION:-}}"

info()  {{ printf "\\033[1;34m→\\033[0m %s\\n" "$1"; }}
ok()    {{ printf "\\033[1;32m✓\\033[0m %s\\n" "$1"; }}
err()   {{ printf "\\033[1;31m✗\\033[0m %s\\n" "$1" >&2; }}

# Detect OS and architecture
detect_platform() {{
    local os arch
    case "$(uname -s)" in
        Linux*)  os="linux" ;;
        Darwin*) os="darwin" ;;
        MINGW*|MSYS*|CYGWIN*) os="windows" ;;
        *) err "Unsupported OS: $(uname -s)"; exit 1 ;;
    esac
    case "$(uname -m)" in
        x86_64|amd64)  arch="amd64" ;;
        aarch64|arm64) arch="arm64" ;;
        *) err "Unsupported architecture: $(uname -m)"; exit 1 ;;
    esac
    echo "${{os}}_${{arch}}"
}}

# Get latest version from GitHub API
get_latest_version() {{
    curl -sf "https://api.github.com/repos/$REPO/releases/latest" \\
        | grep -oP '"tag_name":\\s*"\\K[^"]+' \\
        | sed 's/^v//' \\
        2>/dev/null || echo ""
}}

# Download and install
install_binary() {{
    local platform="$1"
    local version="$2"
    local tmp_dir
    tmp_dir=$(mktemp -d)
    trap "rm -rf $tmp_dir" EXIT

    local url="https://github.com/$REPO/releases/download/v$version/${{BINARY}}-${{platform}}.tar.gz"

    info "Downloading $NAME $version for $platform..."
    if ! curl -sfL "$url" -o "$tmp_dir/archive.tar.gz"; then
        # Try alternative: name_version_platform format
        url="https://github.com/$REPO/releases/download/v$version/${{NAME}}_${{version}}_${{platform}}.tar.gz"
        curl -sfL "$url" -o "$tmp_dir/archive.tar.gz" || {{
            err "Download failed. Check https://github.com/$REPO/releases"
            exit 1
        }}
    fi

    info "Extracting..."
    tar -xzf "$tmp_dir/archive.tar.gz" -C "$tmp_dir"

    # Find the binary
    local bin_path
    bin_path=$(find "$tmp_dir" -name "$BINARY" -type f | head -1)
    if [[ -z "$bin_path" ]]; then
        bin_path=$(find "$tmp_dir" -name "${{BINARY}}*" -type f -executable | head -1)
    fi
    if [[ -z "$bin_path" ]]; then
        err "Binary '$BINARY' not found in archive"
        exit 1
    fi

    # Install to /usr/local/bin or ~/.local/bin
    local install_dir
    if [[ -w "/usr/local/bin" ]]; then
        install_dir="/usr/local/bin"
    else
        install_dir="$HOME/.local/bin"
        mkdir -p "$install_dir"
    fi

    cp "$bin_path" "$install_dir/$BINARY"
    chmod +x "$install_dir/$BINARY"

    ok "$NAME $version installed to $install_dir/$BINARY"
}}

main() {{
    local platform
    platform=$(detect_platform)

    if [[ -z "$VERSION" ]]; then
        VERSION=$(get_latest_version)
        if [[ -z "$VERSION" ]]; then
            err "Could not determine latest version"
            exit 1
        fi
    fi

    info "Platform: $platform"
    info "Version:  $VERSION"

    # Check if already installed
    if command -v "$BINARY" &>/dev/null; then
        local current
        current=$("$BINARY" --version 2>&1 | grep -oP 'v?\\d+\\.\\d+(?:\\.\\d+)?' | head -1 || echo "unknown")
        if [[ "$current" == "$VERSION" ]]; then
            ok "$NAME $VERSION is already installed"
            exit 0
        fi
        info "Updating $NAME from $current to $VERSION"
    fi

    install_binary "$platform" "$VERSION"
}}

main "$@"
"""
    return script


def shell_filename(config: PackageConfig) -> str:
    """Return the shell script filename."""
    return "install.sh"